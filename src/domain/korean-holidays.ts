// 합쳐서 단일 lookup 테이블로. 추가 연도는 여기에 spread.
const KOREAN_HOLIDAYS: Readonly<Record<string, string>> = Object.freeze({
  ...HOLIDAYS_2025,
  ...HOLIDAYS_2026,
  ...HOLIDAYS_2027,
});

/**
 * 주어진 ISODate(YYYY-MM-DD)가 등록된 한국 공휴일이면 표기명, 아니면 null.
 * 테이블에 등록되지 않은 연도는 모두 null을 돌려준다 — 그게 안전한 기본값
 * (오탐보다 미탐을 선호; UI는 공휴일을 단순 "표시 안 함"으로 처리한다).
 */
export function getKoreanHolidayName(iso: ISODate): string | null {
  return KOREAN_HOLIDAYS[iso as unknown as string] ?? null;
}

export function isKoreanHoliday(iso: ISODate): boolean {
  return Object.prototype.hasOwnProperty.call(
    KOREAN_HOLIDAYS,
    iso as unknown as string,
  );
}
